// End-to-end workflows A–E. Usage: BASE_URL=http://localhost:3000 node scripts/e2e-workflows.js
const { chromium } = require('playwright');
const SHOTS = (process.env.SHOTS_DIR || '/tmp') + '/';
const BASE = process.env.BASE_URL || 'http://localhost:3000';
let pass = 0, fail = 0;
const ok = (c, msg) => { if (c) { pass++; console.log('  ✓', msg); } else { fail++; console.log('  ✗', msg); } };

(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
  const p = await ctx.newPage();
  const errors = [];
  p.on('pageerror', (e) => errors.push(e.message));
  p.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  const data = () => p.evaluate(() => JSON.parse(localStorage.getItem('duka.data')));
  const stockOf = async (pid, vid) => (await data()).products.find((x) => x.id === pid).variants.find((v) => v.id === vid).stock;
  const shot = (n) => p.screenshot({ path: SHOTS + n + '.png', fullPage: true });
  const login = async (u, pin) => {
    await p.goto(BASE + '/staff/login');
    await p.fill('#l-user', u); await p.fill('#l-pin', pin);
    await p.click('button[type=submit]');
    await p.waitForURL(/\/staff(\/|$)(?!login)/);
  };
  const logout = async () => { await p.keyboard.press('Escape'); await p.waitForTimeout(100); await p.click('aside >> button[aria-label="Log out"]'); await p.waitForURL(/login/); };

  console.log('Workflow A: customer purchase');
  await p.goto(BASE + '/');
  await p.evaluate(() => localStorage.clear());
  await p.goto(BASE + '/');
  await p.waitForSelector('text=Featured products');
  await p.click('nav[aria-label="Categories"] >> text=Torches');
  await p.waitForURL(/category\/torches/);
  ok((await p.locator('h1').innerText()) === 'Torches', 'category page opens');
  await p.fill('#search-desktop', 'JC-7125'); await p.press('#search-desktop', 'Enter');
  await p.waitForURL(/products\?q=/);
  await p.waitForSelector('text=JC-7125 Rechargeable Torch');
  ok(await p.locator('section[aria-label=Products] li').count() === 1, 'search returns 1 product');
  await p.click('text=JC-7125 Rechargeable Torch');
  await p.waitForURL(/product\//);
  await p.click('button:has-text("Pink")');
  ok(await p.locator('text=SKU DL-').innerText().then((t) => t.endsWith('-4')), 'variant selection updates SKU');
  const before = await stockOf('torch-jc7125', 'torch-jc7125-v4');
  await p.click('button[aria-label="Increase quantity"]');
  await shot('A1-product-d');
  await p.click('button:has-text("Add to cart")');
  await p.goto(BASE + '/cart');
  ok(await p.locator('input[aria-label="Quantity of JC-7125 Rechargeable Torch"]').inputValue() === '2', 'cart has qty 2');
  await p.click('button[aria-label="Increase quantity"]');
  await p.waitForTimeout(150);
  ok(await p.locator('input[aria-label="Quantity of JC-7125 Rechargeable Torch"]').inputValue() === '3', 'cart qty increased to 3');
  await shot('A2-cart-d');
  await p.click('text=Proceed to checkout');
  await p.waitForURL(/checkout/);
  await p.click('button:has-text("Place order")');
  ok(await p.locator('text=Enter your full name.').isVisible(), 'checkout validation shows errors');
  await p.fill('#co-name', 'Wanjiku Test');
  await p.fill('#co-phone', '0712 345 678');
  await p.check('#ful-delivery');
  ok(await p.locator('#pay-cash').isDisabled(), 'cash disabled for delivery');
  await p.check('#zone-zone_2');
  await shot('A3-checkout-d');
  await p.click('button:has-text("Place order")');
  await p.waitForURL(/order\//);
  await p.waitForSelector('text=Simulate: customer enters PIN');
  await shot('A4-stk-d');
  ok(await stockOf('torch-jc7125', 'torch-jc7125-v4') === before - 3, `stock deducted once (${before} → ${before - 3})`);
  await p.click('text=Simulate: customer enters PIN');
  await p.waitForSelector('text=View my order', { timeout: 5000 });
  await p.click('text=View my order');
  const orderNo = (await p.locator('.font-display.text-marigold-500').innerText()).trim();
  ok(/DL-\d+/.test(orderNo), 'order number shown ' + orderNo);
  ok(await p.locator('text=Paid').first().isVisible(), 'payment status paid');
  ok((await data()).orders[0].total === 3 * 300 + 200, 'order total includes zone fee');
  await shot('A5-order-d');
  await p.goto(BASE + '/track');
  await p.fill('#t-num', orderNo); await p.fill('#t-phone', '0799999999'); await p.click('button:has-text("Find my order")');
  await p.waitForSelector('text=No order matches those details');
  ok(true, 'wrong phone rejected');
  await p.fill('#t-phone', '+254712345678'); await p.click('button:has-text("Find my order")');
  await p.waitForSelector('text=Status history');
  ok(await p.locator('ol[aria-label="Order progress"] >> text=Out for delivery').isVisible(), 'tracker shows delivery steps');
  ok(!(await p.locator('ol[aria-label="Order progress"] >> text=Ready for pickup').count()), 'no pickup step on delivery order');

  console.log('Workflow B: staff order processing');
  await p.goto(BASE + '/staff');
  await p.waitForURL(/login/);
  ok(true, 'staff area redirects to login when signed out');
  await login('owner', '1234');
  await p.waitForSelector('text=Sales, last 7 days');
  await shot('B1-dashboard-d');
  await p.click('a[href="/staff/orders"]');
  await p.click(`button:has-text("${orderNo}")`);
  await p.click('button:has-text("Mark packed")');
  await p.click('button:has-text("Send out for delivery")');
  await p.click('button:has-text("Mark delivered")');
  await p.waitForTimeout(200);
  const o = (await data()).orders.find((x) => x.number === orderNo);
  ok(o.status === 'delivered' && o.history.length === 4, 'order moved placed → packed → out → delivered');
  await shot('B2-order-drawer-d');
  // cash order cannot complete before payment
  const cashOrder = (await data()).orders.find((x) => x.paymentMethod === 'cash' && x.status === 'packed');
  await p.goto(BASE + '/staff/orders?open=' + cashOrder.id);
  await p.click('button:has-text("Mark ready for pickup")');
  ok(await p.locator('button:has-text("Mark collected")').isDisabled(), 'cannot mark collected before cash paid');
  await p.click('button:has-text("Mark cash received")');
  await p.click('button:has-text("Mark collected")');
  await p.waitForTimeout(150);
  ok((await data()).orders.find((x) => x.id === cashOrder.id).status === 'collected', 'cash pickup order collected after payment');
  // cancel restores stock once
  const placed = (await data()).orders.find((x) => x.status === 'placed');
  const it = placed.items[0];
  const s0 = await stockOf(it.productId, it.variantId);
  await p.goto(BASE + '/staff/orders?open=' + placed.id);
  await p.click('button:has-text("Cancel order")');
  await p.fill('#c-reason', 'Customer changed mind');
  await p.click('div[role=dialog] >> button:has-text("Cancel order") >> nth=-1');
  await p.waitForTimeout(200);
  ok(await stockOf(it.productId, it.variantId) === s0 + it.qty, 'cancel restocks items');
  ok(!(await p.locator('button:has-text("Cancel order")').count()), 'cancelled order has no further actions');
  await logout();

  console.log('Workflow C: POS');
  await login('cashier', '2345');
  ok(p.url().endsWith('/staff/pos'), 'cashier lands on POS');
  const posBefore = await stockOf('bulb-avc', 'bulb-avc-v2');
  await p.fill('#pos-q', 'DL-001-2'); await p.press('#pos-q', 'Enter');
  await p.fill('#pos-q', 'kettle'); await p.click('text=Ailyons 2.0L Electric Kettle');
  await p.locator('aside >> button[aria-label="Increase quantity"]').first().click();
  ok(await p.locator('aside >> text=Total').isVisible(), 'sale has items');
  await p.click('aside >> button:has-text("Exact")');
  const total = 150 * 2 + 1450;
  await p.fill('#pos-cash', '2000');
  ok(await p.locator('aside >> text=Change').isVisible(), 'change shown');
  await shot('C1-pos-d');
  await p.click('aside >> button:has-text("Complete sale")');
  await p.waitForSelector('text=Sale complete');
  ok(await p.locator('text=Give change').isVisible(), 'receipt shows change to give');
  await shot('C2-receipt-d');
  ok(await stockOf('bulb-avc', 'bulb-avc-v2') === posBefore - 2, 'POS deducted stock');
  const sale = (await data()).posSales[0];
  ok(sale.total === total && sale.change === 2000 - total, `sale total ${sale.total}, change ${sale.change}`);
  await p.click('button:has-text("New sale")');
  await p.goto(BASE + '/staff/settings');
  ok(await p.locator('text=You don’t have access to this page').isVisible(), 'cashier blocked from settings');
  ok(!(await p.locator('aside >> a[href="/staff/products"]').count()), 'cashier nav hides products');
  await logout();

  console.log('Workflow D: inventory');
  await login('stock', '3456');
  ok(p.url().endsWith('/staff/inventory'), 'clerk lands on inventory');
  const invBefore = await stockOf('radio-ns1587bt', 'radio-ns1587bt-v1');
  await p.fill('#inv-q', 'NS-1587');
  await p.click('button[aria-label^="Adjust stock for NS-1587BT"]:visible');
  await p.fill('#a-qty', '10');
  await p.click('button:has-text("Save")');
  await p.waitForTimeout(200);
  ok(await stockOf('radio-ns1587bt', 'radio-ns1587bt-v1') === invBefore + 10, `stock in recorded (${invBefore} → ${invBefore + 10})`);
  await p.click('button[role=tab]:has-text("Movement log")');
  ok(await p.locator('tbody >> tr').first().innerText().then((t) => t.includes('Faith Chebet') && t.includes('+10')), 'movement log shows staff + change');
  await shot('D1-inventory-log-d');
  await p.click('a[href="/staff/products"]');
  await p.waitForSelector('text=Demonstration catalogue');
  const body = await p.locator('main').innerText();
  ok(!/KES\s?\d/.test(body), 'clerk sees no prices on products page');
  await p.goto(BASE + '/staff/pos');
  ok(await p.locator('text=You don’t have access to this page').isVisible(), 'clerk blocked from POS');
  await p.goto(BASE + '/product/ns-1587bt-solar-radio-with-bluetooth');
  ok(await p.locator('text=10 in stock').isVisible(), 'storefront shows new availability');
  await p.goto(BASE + '/staff/inventory'); await logout();

  console.log('Workflow E: catalogue management');
  await login('owner', '1234');
  await p.goto(BASE + '/staff/products');
  await p.click('button:has-text("Add product")');
  await p.fill('#p-name', 'Demo LED Strip Light');
  await p.selectOption('#p-cat', 'lighting');
  await p.fill('#p-brand', 'Dplight');
  await p.fill('#v0l', '5 m'); await p.fill('#v0p', '850'); await p.fill('#v0o', '12');
  await p.click('button:has-text("Add variant")');
  await p.fill('#v1l', '10 m'); await p.fill('#v1p', '1500'); await p.fill('#v1o', '6');
  await p.setInputFiles('input[type=file]', require('path').join(__dirname, '../public/products/cob-unit-1.webp'));
  await p.waitForSelector('text=MAIN');
  await shot('E1-product-form-d');
  await p.click('div[role=dialog] >> button:has-text("Add product")');
  await p.waitForTimeout(300);
  const np = (await data()).products.find((x) => x.name === 'Demo LED Strip Light');
  ok(np && np.published && np.variants.length === 2 && np.variants[1].stock === 6, 'product created with variants & opening stock');
  ok(np.images[0].startsWith('idb:'), 'photo stored in IndexedDB');
  await p.goto(BASE + '/products?q=LED%20Strip');
  await p.waitForSelector('text=Demo LED Strip Light');
  ok(true, 'new product visible on storefront');
  await p.waitForTimeout(500);
  await shot('E2-storefront-new-d');
  await p.goto(BASE + '/staff/products');
  await p.fill('#pr-q', 'LED Strip');
  await p.click('button[aria-label="Edit Demo LED Strip Light"]');
  await p.fill('#v0p', '900');
  await p.click('div[role=dialog] >> button:has-text("Save changes")');
  await p.waitForTimeout(200);
  ok((await data()).products.find((x) => x.id === np.id).variants[0].price === 900, 'edit saved price');
  await p.click('button[aria-label="Hide Demo LED Strip Light"]');
  await p.waitForTimeout(300);
  await shot('E3-after-hide');
  await p.goto(BASE + '/products?q=LED%20Strip');
  await p.waitForSelector('section[aria-label=Products] li');
  ok(!(await p.locator('text=Demo LED Strip Light').count()), 'unpublished product removed from storefront');
  await p.goto(BASE + '/product/' + np.slug);
  ok(await p.locator("text=This product isn't available").isVisible(), 'hidden product page shows unavailable state');

  console.log('\nJS errors:', errors.length ? errors : 'none');
  console.log(`\n${pass} passed, ${fail} failed`);
  await b.close();
  process.exit(fail ? 1 : 0);
})().catch((e) => { console.error('FATAL', e.message); process.exit(2); });
